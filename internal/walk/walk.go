// Package walk holds what every importer shares: valid rotini names, argument names read from
// a usage line, function positions for hook pointers, and the build facts a description's
// source names.
package walk

import (
	"path"
	"path/filepath"
	"reflect"
	"runtime"
	"runtime/debug"
	"strconv"
	"strings"
	"unicode"

	imp "github.com/go-rotini/import"
)

const importerModule = "github.com/go-rotini/import"

// IsLetter reports whether r is an ASCII letter.
func IsLetter(r rune) bool { return (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') }

// IsDigit reports whether r is an ASCII digit.
func IsDigit(r rune) bool { return r >= '0' && r <= '9' }

// CommandName makes s a valid rotini command or flag name: a letter, then letters, digits,
// '_' and '-'. Characters before the first letter are dropped, other characters become
// '-', and a name with no letter becomes "cmd".
func CommandName(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case IsLetter(r):
			b.WriteRune(r)
		case b.Len() == 0:
		case IsDigit(r) || r == '_' || r == '-':
			b.WriteRune(r)
		default:
			b.WriteByte('-')
		}
	}
	if b.Len() == 0 {
		return "cmd"
	}
	return b.String()
}

// ValidName reports whether s is already a valid rotini command or flag name.
func ValidName(s string) bool { return s != "" && CommandName(s) == s }

// JoinPath appends name to a command path.
func JoinPath(parent, name string) string {
	if parent == "" {
		return name
	}
	return parent + " " + name
}

// ArgName turns a placeholder into an argument name: lower case letters, digits and '_',
// starting with a letter.
func ArgName(s string) string {
	var b strings.Builder
	under := false
	for _, r := range strings.ToLower(s) {
		if IsLetter(r) || IsDigit(r) {
			if under && b.Len() > 0 {
				b.WriteByte('_')
			}
			under = false
			b.WriteRune(r)
			continue
		}
		under = true
	}
	out := b.String()
	if out != "" && !IsLetter(rune(out[0])) {
		out = "arg_" + out
	}
	return out
}

// UniqueNames gives repeated argument names a numeric suffix: name, name_2, name_3.
func UniqueNames(args []*imp.Argument) {
	used := map[string]bool{}
	for _, a := range args {
		name := a.Name
		for n := 2; used[name]; n++ {
			name = a.Name + "_" + strconv.Itoa(n)
		}
		a.Name = name
		used[name] = true
	}
}

// SplitExamples splits an example block into its examples: one per line, trimmed, with a
// line that ends in a backslash or leaves a quote open joined to the lines that complete it.
// Comment lines ("# create a PR") are returned apart, as comments.
func SplitExamples(ex string) (examples, comments []string) {
	var lines []string
	for _, l := range strings.Split(ex, "\n") {
		if l = strings.TrimSpace(l); l != "" {
			lines = append(lines, l)
		}
	}
	for i := 0; i < len(lines); i++ {
		if comment, ok := strings.CutPrefix(lines[i], "#"); ok {
			comments = append(comments, strings.TrimSpace(comment))
			continue
		}
		end := i
		for end+1 < len(lines) && continues(strings.Join(lines[i:end+1], "\n")) {
			end++
		}
		if continues(strings.Join(lines[i:end+1], "\n")) {
			end = i // never completed: an apostrophe in prose, not a quote
		}
		examples = append(examples, strings.Join(lines[i:end+1], "\n"))
		i = end
	}
	return examples, comments
}

// continues reports whether a shell command line goes on past its end: it ends in a
// backslash or leaves a quote open. Only a quote that starts a word or follows '=' opens:
// one inside a word is taken for an apostrophe in prose ("don't").
func continues(s string) bool {
	var quote, prev rune
	escaped := false
	for _, r := range s {
		switch {
		case escaped:
			escaped = false
		case r == '\\' && quote != '\'':
			escaped = true
		case quote != 0:
			if r == quote {
				quote = 0
			}
		case (r == '\'' || r == '"') && (prev == 0 || prev == '=' || unicode.IsSpace(prev)):
			quote = r
		}
		prev = r
	}
	return escaped || quote != 0
}

// FuncValue returns f's code pointer, or 0 for a nil or non-function value.
func FuncValue(f any) uintptr {
	v := reflect.ValueOf(f)
	if !v.IsValid() || v.Kind() != reflect.Func || v.IsNil() {
		return 0
	}
	return v.Pointer()
}

// FuncName returns f's full name as the Go runtime reports it, or "" for a nil or
// non-function value.
func FuncName(f any) string {
	pc := FuncValue(f)
	if pc == 0 {
		return ""
	}
	if fn := runtime.FuncForPC(pc); fn != nil {
		return fn.Name()
	}
	return "?"
}

// FuncPos returns a function's name, file and line. A file in the module cache is given
// relative to it ("example.com/x@v1.2.3/cmd.go"). A method value ("o.run") is located at the
// method it calls, and named after it; when the method cannot be found, file and line are
// empty.
func FuncPos(f any) (name, file string, line int) {
	pc := FuncValue(f)
	if pc == 0 {
		return "", "", 0
	}
	fn := runtime.FuncForPC(pc)
	if fn == nil {
		return "?", "", 0
	}
	name = fn.Name()
	file, line = fn.FileLine(pc)
	if method, ok := strings.CutSuffix(name, "-fm"); ok || file == "<autogenerated>" {
		name = method
		file, line = methodPos(fn, method)
	}
	return name, ModulePath(file), line
}

// ModulePath gives a file in the module cache relative to it: "example.com/x@v1.2.3/cmd.go".
// Any other file is returned as it is.
func ModulePath(file string) string {
	if dir := modCache(); dir != "" {
		if rest, ok := strings.CutPrefix(file, dir+"/"); ok {
			return rest
		}
	}
	// A module cache the environment does not name: cut only where the remainder names a
	// module@version directory.
	if i := strings.LastIndex(file, "/pkg/mod/"); i >= 0 {
		rest := file[i+len("/pkg/mod/"):]
		if at := strings.Index(rest, "@"); at > 0 && strings.Contains(rest[at:], "/") {
			return rest
		}
	}
	return file
}

// SameFunc reports whether a and b are the same function.
func SameFunc(a, b any) bool { return FuncValue(a) == FuncValue(b) }

// funcFile returns the file that defines f, or "".
func funcFile(f any) string {
	pc := FuncValue(f)
	if pc == 0 {
		return ""
	}
	fn := runtime.FuncForPC(pc)
	if fn == nil {
		return ""
	}
	file, _ := fn.FileLine(pc)
	return file
}

// DefinedBeside reports whether f is defined in the directory of the file that defines ref, a
// top-level function of a framework's package. A closure the compiler inlined into its
// caller can carry the caller's name, depending on the Go release, but always keeps the file
// it is written in, so this recognizes a framework's own closures where their names do not.
func DefinedBeside(f, ref any) bool {
	file, refFile := funcFile(f), funcFile(ref)
	if file == "" || refFile == "" || file == "<autogenerated>" {
		return false
	}
	return path.Dir(filepath.ToSlash(file)) == path.Dir(filepath.ToSlash(refFile))
}

// Source names the framework, the version of its module in the running program and the
// importer's own version, as far as the build records them. ref is a top-level function of
// the framework's module. A test binary built by a Go release before 1.27 records no
// dependencies, so a version missing there is read from the module cache directory that ref's
// source file is in, such as "github.com/spf13/cobra@v1.8.0".
func Source(framework, module string, ref any) imp.Source {
	s := imp.Source{Framework: framework}
	if bi, ok := debug.ReadBuildInfo(); ok {
		if bi.Main.Path == importerModule {
			s.Importer = bi.Main.Version
		}
		for _, d := range bi.Deps {
			switch d.Path {
			case module:
				s.Version = moduleVersion(d)
			case importerModule:
				s.Importer = moduleVersion(d)
			}
		}
	}
	if s.Version == "" {
		s.Version = fileVersion(funcFile(ref), module)
	}
	if s.Importer == "" {
		s.Importer = fileVersion(funcFile(Source), importerModule)
	}
	return s
}

// fileVersion reads module's version from file's path when the file is in that module's
// directory of a module cache ("…/github.com/spf13/cobra@v1.8.0/args.go"), else returns "".
func fileVersion(file, module string) string {
	file = filepath.ToSlash(file)
	prefix := escapeModule(module) + "@"
	for from := 0; ; {
		i := strings.Index(file[from:], prefix)
		if i < 0 {
			return ""
		}
		i += from
		if i == 0 || file[i-1] == '/' {
			version, _, ok := strings.Cut(file[i+len(prefix):], "/")
			if ok && version != "" {
				return version
			}
		}
		from = i + 1
	}
}

// escapeModule writes a module path as the module cache does, with each upper-case letter
// as '!' and its lower-case form.
func escapeModule(module string) string {
	var b strings.Builder
	for _, r := range module {
		if 'A' <= r && r <= 'Z' {
			b.WriteByte('!')
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}

func moduleVersion(m *debug.Module) string {
	if m.Replace != nil && m.Replace.Version != "" {
		return m.Replace.Version
	}
	return m.Version
}

// DependsOn reports whether the running program links the module at path, as its build
// records it. A test binary built by Go before 1.27 records no dependencies, so there it
// reports false.
func DependsOn(path string) bool {
	bi, ok := debug.ReadBuildInfo()
	if !ok {
		return false
	}
	for _, d := range bi.Deps {
		if d.Path == path {
			return true
		}
	}
	return false
}
